plugins {
    alias(libs.plugins.mokelab.kmp.library.compose)
}

@Suppress("UNCHECKED_CAST")
val enabledFeatures = gradle.extra["playground.features"] as List<String>

// 有効な feature の Koin モジュール一覧 (FeatureModules.kt) を生成する。
// 各 feature は自分のパッケージ直下に `val featureModule: Module` を置く決まり。
val generateFeatureModules = tasks.register("generateFeatureModules") {
    val features = enabledFeatures
    val outputDir = layout.buildDirectory.dir("generated/featureModules/commonMain/kotlin")
    inputs.property("features", features)
    outputs.dir(outputDir)
    doLast {
        val refs = features.joinToString("") { name ->
            "    com.mokelab.playground.feature.${name.replace(':', '.')}.featureModule,\n"
        }
        val file = outputDir.get().file("com/mokelab/playground/FeatureModules.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by :shared:generateFeatureModules. Do not edit.
            |package com.mokelab.playground
            |
            |import org.koin.core.module.Module
            |
            |internal val featureModules: List<Module> = listOf(
            |$refs)
            |""".trimMargin()
        )
    }
}

kotlin {
    listOf(
        iosArm64(),
        iosSimulatorArm64()
    ).forEach { iosTarget ->
        iosTarget.binaries.framework {
            baseName = "Shared"
            isStatic = true
        }
    }

    sourceSets {
        commonMain {
            kotlin.srcDir(generateFeatureModules)
            dependencies {
                implementation(libs.devportal)
                api(libs.koin.core)
                enabledFeatures.forEach { implementation(project(":feature:$it")) }
            }
        }
    }
}
